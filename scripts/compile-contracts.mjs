import fs from "node:fs";
import path from "node:path";
import solc from "solc";
const sources = Object.fromEntries(
  ["Pinhaotuan", "TestUSDC", "DemoUSD"].map((name) => [
    `contracts/${name}.sol`,
    { content: fs.readFileSync(`contracts/${name}.sol`, "utf8") },
  ]),
);
const input = {
  language: "Solidity",
  sources,
  settings: {
    evmVersion: "shanghai",
    viaIR: true,
    optimizer: { enabled: true, runs: 200 },
    outputSelection: {
      "*": {
        "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"],
      },
    },
  },
};
const output = JSON.parse(
  solc.compile(JSON.stringify(input), {
    import: (name) => {
      try {
        return {
          contents: fs.readFileSync(path.resolve("node_modules", name), "utf8"),
        };
      } catch {
        return { error: `Import not found: ${name}` };
      }
    },
  }),
);
for (const error of output.errors || [])
  console[error.severity === "error" ? "error" : "warn"](
    error.formattedMessage,
  );
if (output.errors?.some((error) => error.severity === "error")) process.exit(1);
fs.mkdirSync("artifacts/contracts", { recursive: true });
fs.mkdirSync("src/generated", { recursive: true });
const exports = [];
for (const name of ["Pinhaotuan", "TestUSDC", "DemoUSD"]) {
  const result = output.contracts[`contracts/${name}.sol`][name];
  const artifact = {
    contractName: name,
    compiler: solc.version(),
    abi: result.abi,
    bytecode: `0x${result.evm.bytecode.object}`,
    deployedBytecode: `0x${result.evm.deployedBytecode.object}`,
  };
  fs.writeFileSync(
    `artifacts/contracts/${name}.json`,
    JSON.stringify(artifact, null, 2),
  );
  exports.push(
    `export const ${name === "Pinhaotuan" ? "pinhaotuanAbi" : name === "DemoUSD" ? "demoTokenAbi" : "testTokenAbi"} = ${JSON.stringify(result.abi)} as const;`,
  );
  console.log(
    `${name}: ${result.evm.deployedBytecode.object.length / 2} deployed bytes`,
  );
}
fs.writeFileSync(
  "src/generated/abi.ts",
  "// Generated by npm run contracts:compile.\n" + exports.join("\n") + "\n",
);
